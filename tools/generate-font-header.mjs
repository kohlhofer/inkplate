#!/usr/bin/env node
// Converts the glyph table in font/bedstead.c into the board renderer's
// font_data.h. Same glyph set and bitmaps as the archived relay's
// archive/relay/font/font-data.js (same parsing, aliases and SAA5050 rounding;
// `make test-native` checks every glyph against it), emitted as const arrays
// the ESP32 keeps in flash: a sorted codepoint table and 24 rows per glyph.
// Run `make font` when bedstead.c changes; the output is committed.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "font", "bedstead.c");
const outPath = path.join(root, "sketches", "videotext", "src", "render", "font_data.h");

const CELL_WIDTH = 12;
const CELL_HEIGHT = 24;
const SRC_W = 6;
const SRC_H = 10;
const TOP_PAD = 2;

// Drawn procedurally by the renderer, so any Bedstead versions are skipped.
function isProcedural(cp) {
    return (cp >= 0x2500 && cp <= 0x259f) || (cp >= 0x1fb00 && cp <= 0x1fbff);
}

// The regex requires a name string after the codepoint, exactly as the relay's
// generator did; entries without one (U+FFFD among them) are not in the set.
function parseGlyphs(src) {
    const re = /\{\{\s*([0-7][0-7,\s]*)\}\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*"[^"]*"/g;
    const glyphs = new Map();
    let m;
    while ((m = re.exec(src))) {
        const cp = parseInt(m[2], 16);
        // The SAA5050 set comes first in the file; later duplicates are variants.
        if (glyphs.has(cp) || isProcedural(cp)) continue;
        const rows = m[1]
            .split(",")
            .map((s) => s.trim())
            .filter(Boolean)
            .map((s) => parseInt(s, 8));
        while (rows.length < SRC_H) rows.push(0);
        glyphs.set(cp, rows);
    }
    return glyphs;
}

// Every source pixel doubled to 2x2, then the SAA5050's character rounding
// fills the two half-pixels on either side of each diagonal step.
function renderRounded(rows) {
    const src = (x, y) => (x >= 0 && x < SRC_W && y >= 0 && y < SRC_H ? (rows[y] >> (SRC_W - 1 - x)) & 1 : 0);
    const hi = Array.from({ length: SRC_H * 2 }, () => new Array(SRC_W * 2).fill(0));
    for (let y = 0; y < SRC_H; y++) {
        for (let x = 0; x < SRC_W; x++) {
            if (!src(x, y)) continue;
            hi[2 * y][2 * x] = hi[2 * y][2 * x + 1] = hi[2 * y + 1][2 * x] = hi[2 * y + 1][2 * x + 1] = 1;
        }
    }
    const set = (x, y) => {
        if (x >= 0 && x < SRC_W * 2 && y >= 0 && y < SRC_H * 2) hi[y][x] = 1;
    };
    for (let y = 0; y < SRC_H - 1; y++) {
        for (let x = 0; x < SRC_W - 1; x++) {
            const a = src(x, y);
            const b = src(x + 1, y);
            const c = src(x, y + 1);
            const d = src(x + 1, y + 1);
            if (a && d && !b && !c) {
                set(2 * x + 2, 2 * y + 1);
                set(2 * x + 1, 2 * y + 2);
            }
            if (b && c && !a && !d) {
                set(2 * x + 1, 2 * y + 1);
                set(2 * x + 2, 2 * y + 2);
            }
        }
    }
    const out = new Array(CELL_HEIGHT).fill(0);
    for (let y = 0; y < SRC_H * 2; y++) {
        let bits = 0;
        for (let x = 0; x < CELL_WIDTH; x++) bits = (bits << 1) | hi[y][x];
        out[TOP_PAD + y] = bits;
    }
    return out;
}

const glyphs = parseGlyphs(readFileSync(sourcePath, "utf8"));

// Codepoints Bedstead lacks that agent-written text uses.
glyphs.set(0xa0, glyphs.get(0x20)); // no-break space
glyphs.set(0xad, glyphs.get(0x2d)); // soft hyphen
glyphs.set(0x2026, glyphs.get(0x2e).map((row) => (row ? 0o25 : 0))); // ellipsis: three dots on the period's row

const missing = [];
for (let cp = 0x20; cp <= 0x7e; cp++) if (!glyphs.has(cp)) missing.push(cp);
for (let cp = 0xa0; cp <= 0xff; cp++) if (!glyphs.has(cp)) missing.push(cp);
if (missing.length > 0) {
    throw new Error(`missing glyphs for codepoints: ${missing.join(", ")}`);
}

const codepoints = [...glyphs.keys()].sort((a, b) => a - b);
const hex = (n, width) => `0x${n.toString(16).padStart(width, "0")}`;

const codepointLines = [];
for (let i = 0; i < codepoints.length; i += 8) {
    codepointLines.push(`    ${codepoints.slice(i, i + 8).map((cp) => `${hex(cp, 5)},`).join(" ")}`);
}

const rowLines = codepoints.map((cp) => {
    const rows = renderRounded(glyphs.get(cp)).map((r) => `${hex(r, 3)},`);
    return `    ${rows.join("")} // U+${cp.toString(16).toUpperCase().padStart(4, "0")}`;
});

const output = `// Generated by tools/generate-font-header.mjs from font/bedstead.c. Do not edit by hand.
// Bedstead (CC0), drawn SAA5050-style: pixels doubled, diagonals rounded, 12x24 cells.
#pragma once

#include <cstdint>

namespace vt {
namespace font {

constexpr int GLYPH_WIDTH = ${CELL_WIDTH};
constexpr int GLYPH_HEIGHT = ${CELL_HEIGHT};
constexpr int GLYPH_COUNT = ${codepoints.length};

// Ascending, so glyphRows() can binary-search it.
inline constexpr std::uint32_t GLYPH_CODEPOINTS[GLYPH_COUNT] = {
${codepointLines.join("\n")}
};

// GLYPH_HEIGHT rows per glyph, in GLYPH_CODEPOINTS order; bit 11 = leftmost pixel.
inline constexpr std::uint16_t GLYPH_ROWS[GLYPH_COUNT * GLYPH_HEIGHT] = {
${rowLines.join("\n")}
};

// The glyph's GLYPH_HEIGHT rows, or nullptr when the font has no such codepoint.
inline const std::uint16_t* glyphRows(char32_t codepoint) {
    int lo = 0;
    int hi = GLYPH_COUNT - 1;
    while (lo <= hi) {
        const int mid = lo + (hi - lo) / 2;
        const std::uint32_t cp = GLYPH_CODEPOINTS[mid];
        if (cp == codepoint) return GLYPH_ROWS + mid * GLYPH_HEIGHT;
        if (cp < codepoint) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return nullptr;
}

}  // namespace font
}  // namespace vt
`;

writeFileSync(outPath, output);
console.log(`wrote ${codepoints.length} glyphs to ${path.relative(root, outPath)}`);
